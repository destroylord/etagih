<?php

use App\Support\SpreadsheetReader;
use App\Support\XlsxWriter;

function tempFileWith(string $content, string $ext): string
{
    $path = tempnam(sys_get_temp_dir(), 'ssr').'.'.$ext;
    file_put_contents($path, $content);

    return $path;
}

afterEach(function () {
    SpreadsheetReader::$forcePureZip = false;
});

it('reads comma separated csv with BOM and quoted fields', function () {
    $csv = "\xEF\xBB\xBFnama,email,alamat\r\n\"Budi, S.Kom\",budi@example.com,\"Jl. Mawar \"\"No. 1\"\"\nBandung\"\r\n\r\nSiti,siti@example.com,\r\n";

    $rows = (new SpreadsheetReader)->parseCsv($csv);

    expect($rows)->toBe([
        1 => ['nama', 'email', 'alamat'],
        2 => ['Budi, S.Kom', 'budi@example.com', "Jl. Mawar \"No. 1\"\nBandung"],
        4 => ['Siti', 'siti@example.com', null],
    ]);
});

it('detects semicolon and tab delimiters', function () {
    $reader = new SpreadsheetReader;

    expect($reader->parseCsv("nama;tarif\nBudi;150.000,50\n"))
        ->toBe([1 => ['nama', 'tarif'], 2 => ['Budi', '150.000,50']])
        ->and($reader->parseCsv("nama\temail\nBudi\tb@x.id\n"))
        ->toBe([1 => ['nama', 'email'], 2 => ['Budi', 'b@x.id']]);
});

it('converts windows-1252 csv to utf-8', function () {
    $rows = (new SpreadsheetReader)->parseCsv("nama\nCaf\xE9 Jaya\n");

    expect($rows[2][0])->toBe('Café Jaya');
});

it('reads a csv file from disk by extension', function () {
    $path = tempFileWith("nama\nBudi\n", 'csv');

    expect((new SpreadsheetReader)->read($path))->toBe([1 => ['nama'], 2 => ['Budi']]);
    unlink($path);
});

it('reads xlsx generated by XlsxWriter (inline strings, numbers, first sheet only)', function (bool $pure) {
    SpreadsheetReader::$forcePureZip = $pure;

    $writer = new XlsxWriter;
    $writer->addSheet('Klien', [
        [['v' => 'nama', 's' => XlsxWriter::XF_HEADER], 'telepon', 'tarif'],
        ['Budi', '0812', 150000],
        [null, null, null],
        ['Siti', null, 99.5],
    ]);
    $writer->addSheet('Lain', [['bukan', 'ini']]);
    $path = tempFileWith($writer->build(), 'xlsx');

    $rows = (new SpreadsheetReader)->read($path);

    expect($rows)->toBe([
        1 => ['nama', 'telepon', 'tarif'],
        2 => ['Budi', '0812', 150000],
        4 => ['Siti', null, 99.5],
    ]);
    unlink($path);
})->with(['ZipArchive' => false, 'pure php zip' => true]);

it('reads shared strings and deflated xlsx entries', function (bool $pure) {
    SpreadsheetReader::$forcePureZip = $pure;
    $ns = 'http://schemas.openxmlformats.org/spreadsheetml/2006/main';

    $path = tempnam(sys_get_temp_dir(), 'ssr').'.xlsx';
    $zip = new ZipArchive;
    $zip->open($path, ZipArchive::CREATE | ZipArchive::OVERWRITE);
    $zip->addFromString('xl/workbook.xml', '<workbook xmlns="'.$ns.'" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="Data" sheetId="1" r:id="rId7"/></sheets></workbook>');
    $zip->addFromString('xl/_rels/workbook.xml.rels', '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId7" Type="worksheet" Target="worksheets/data.xml"/></Relationships>');
    $zip->addFromString('xl/sharedStrings.xml', '<sst xmlns="'.$ns.'"><si><t>Nama</t></si><si><r><t>Bu</t></r><r><t>di</t></r></si><si><t> E-mail </t></si></sst>');
    $zip->addFromString('xl/worksheets/data.xml', '<worksheet xmlns="'.$ns.'"><sheetData>'
        .'<row r="1"><c r="A1" t="s"><v>0</v></c><c r="C1" t="s"><v>2</v></c></row>'
        .'<row r="3"><c r="A3" t="s"><v>1</v></c><c r="B3" t="b"><v>1</v></c><c r="C3" t="str"><v>b@x.id</v></c><c r="D3"><v>6.2812345678E+12</v></c></row>'
        .'</sheetData></worksheet>');
    $zip->close();

    $rows = (new SpreadsheetReader)->read($path);

    expect($rows)->toBe([
        1 => ['Nama', null, 'E-mail'],
        3 => ['Budi', 'TRUE', 'b@x.id', 6281234567800],
    ]);
    unlink($path);
})->with(['ZipArchive' => false, 'pure php zip' => true]);

it('rejects xlsx whose uncompressed content exceeds the limit (zip bomb)', function (bool $pure) {
    SpreadsheetReader::$forcePureZip = $pure;
    $ns = 'http://schemas.openxmlformats.org/spreadsheetml/2006/main';

    $path = tempnam(sys_get_temp_dir(), 'ssr').'.xlsx';
    $zip = new ZipArchive;
    $zip->open($path, ZipArchive::CREATE | ZipArchive::OVERWRITE);
    $zip->addFromString('xl/worksheets/sheet1.xml', '<worksheet xmlns="'.$ns.'"><sheetData>'.str_repeat(' ', 300_000).'</sheetData></worksheet>');
    $zip->close();

    expect(filesize($path))->toBeLessThan(10_000);

    expect(fn () => (new SpreadsheetReader(maxUncompressedBytes: 100_000))->read($path))
        ->toThrow(RuntimeException::class, 'terlalu besar');
    unlink($path);
})->with(['ZipArchive' => false, 'pure php zip' => true]);

it('rejects corrupt xlsx and unsupported extensions', function () {
    $path = tempFileWith('bukan zip', 'xlsx');

    expect(fn () => (new SpreadsheetReader)->read($path))->toThrow(RuntimeException::class)
        ->and(fn () => (new SpreadsheetReader)->read($path, 'pdf'))->toThrow(RuntimeException::class, 'tidak didukung');
    unlink($path);
});

it('enforces the row limit', function () {
    $reader = new SpreadsheetReader(maxRows: 3);
    $ok = "nama\n".implode("\n", ['a', 'b', 'c']);
    $tooMany = $ok."\nd";

    expect($reader->parseCsv($ok))->toHaveCount(4)
        ->and(fn () => $reader->parseCsv($tooMany))->toThrow(RuntimeException::class, 'lebih dari 3 baris');
});
